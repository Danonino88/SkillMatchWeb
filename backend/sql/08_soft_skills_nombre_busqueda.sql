CREATE TABLE IF NOT EXISTS soft_skills_preguntas (
  id_pregunta INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  competencia VARCHAR(60) NOT NULL CHECK (competencia IN (
    'comunicacion',
    'trabajo_equipo',
    'liderazgo',
    'resolucion_problemas',
    'adaptabilidad',
    'profesionalismo'
  )),
  pregunta TEXT NOT NULL,
  orden INTEGER NOT NULL DEFAULT 1,
  activa BOOLEAN NOT NULL DEFAULT true
);

CREATE TABLE IF NOT EXISTS soft_skills_resultados (
  id_resultado INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_estudiante INTEGER NOT NULL REFERENCES estudiantes(id_estudiante) ON DELETE CASCADE,
  puntaje_total INTEGER NOT NULL DEFAULT 0 CHECK (puntaje_total BETWEEN 0 AND 100),
  comunicacion INTEGER NOT NULL DEFAULT 0 CHECK (comunicacion BETWEEN 0 AND 100),
  trabajo_equipo INTEGER NOT NULL DEFAULT 0 CHECK (trabajo_equipo BETWEEN 0 AND 100),
  liderazgo INTEGER NOT NULL DEFAULT 0 CHECK (liderazgo BETWEEN 0 AND 100),
  resolucion_problemas INTEGER NOT NULL DEFAULT 0 CHECK (resolucion_problemas BETWEEN 0 AND 100),
  adaptabilidad INTEGER NOT NULL DEFAULT 0 CHECK (adaptabilidad BETWEEN 0 AND 100),
  profesionalismo INTEGER NOT NULL DEFAULT 0 CHECK (profesionalismo BETWEEN 0 AND 100),
  respuestas JSONB NOT NULL DEFAULT '[]'::jsonb,
  fecha_realizacion TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_soft_skills_resultados_estudiante_fecha
  ON soft_skills_resultados(id_estudiante, fecha_realizacion DESC);

