BEGIN;

-- Permite quitar acentos en busquedas: Hernandez = Hernandez.
CREATE EXTENSION IF NOT EXISTS unaccent;

-- Nombre normalizado para busqueda.
ALTER TABLE usuarios
  ADD COLUMN IF NOT EXISTS nombre_busqueda TEXT;

CREATE OR REPLACE FUNCTION skillmatch_normalizar_nombre(valor TEXT)
RETURNS TEXT
LANGUAGE SQL
STABLE
AS $$
  SELECT regexp_replace(
    trim(
      regexp_replace(
        lower(public.unaccent(coalesce(valor, ''))),
        '\m(de|del|la|las|los|y)\M', ' ', 'g'
      )
    ),
    '\s+', ' ', 'g'
  );
$$;

CREATE OR REPLACE FUNCTION trg_usuarios_nombre_busqueda()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
  NEW.nombre_busqueda := skillmatch_normalizar_nombre(
    coalesce(NEW.nombre, '') || ' ' || coalesce(NEW.apellido, '')
  );
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS usuarios_nombre_busqueda_aiu ON usuarios;
CREATE TRIGGER usuarios_nombre_busqueda_aiu
BEFORE INSERT OR UPDATE OF nombre, apellido ON usuarios
FOR EACH ROW
EXECUTE FUNCTION trg_usuarios_nombre_busqueda();

UPDATE usuarios
SET nombre_busqueda = skillmatch_normalizar_nombre(
  coalesce(nombre, '') || ' ' || coalesce(apellido, '')
);

CREATE INDEX IF NOT EXISTS idx_usuarios_nombre_busqueda
  ON usuarios USING gin (to_tsvector('simple', coalesce(nombre_busqueda, '')));

